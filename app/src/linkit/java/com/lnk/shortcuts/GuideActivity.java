    @Override
    protected void onCreate(Bundle b) {
        super.onCreate(b);
        getWindow().setStatusBarColor(Ui.bg(this));
        getWindow().setNavigationBarColor(Ui.bg(this));
        if (!Ui.night(this)) {
            getWindow().getDecorView().setSystemUiVisibility(
                    View.SYSTEM_UI_FLAG_LIGHT_STATUS_BAR | View.SYSTEM_UI_FLAG_LIGHT_NAVIGATION_BAR);
        }

        LinearLayout root = new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setBackgroundColor(Ui.bg(this));
        Ui.rtl(root);

        LinearLayout head = new LinearLayout(this);
        head.setOrientation(LinearLayout.HORIZONTAL);
        head.setGravity(Gravity.CENTER_VERTICAL);
        head.setPadding(Ui.dp(this, 8), Ui.dp(this, 12), Ui.dp(this, 20), Ui.dp(this, 4));
        TextView back = Ui.label(this, "→", 26, Ui.text(this), true);
        back.setGravity(Gravity.CENTER);
        back.setPadding(Ui.dp(this, 14), Ui.dp(this, 4), Ui.dp(this, 14), Ui.dp(this, 4));
        back.setClickable(true);
        back.setOnClickListener(v -> finish());
        head.addView(back);
        head.addView(Ui.label(this, "מדריך: מה אפשר לעשות עם LinkIt", 20, Ui.text(this), true));
        root.addView(head);

        ScrollView sv = new ScrollView(this);
        LinearLayout col = new LinearLayout(this);
        col.setOrientation(LinearLayout.VERTICAL);
        col.setPadding(Ui.dp(this, 16), Ui.dp(this, 0), Ui.dp(this, 16), Ui.dp(this, 24));
        sv.addView(col);
        root.addView(sv, new LinearLayout.LayoutParams(Ui.MATCH, 0, 1f));

        TextView intro = Ui.label(this,
                "הקש על נושא כדי לפתוח אותו. LinkIt יוצרת קיצורי דרך לכל דבר במכשיר, ומנהלת אותם במקום אחד, בלי אינטרנט.",
                14, Ui.sub(this), false);
        intro.setPadding(Ui.dp(this, 6), Ui.dp(this, 4), Ui.dp(this, 6), Ui.dp(this, 4));
        col.addView(intro);

        boolean first = true;
        for (String[] g : GUIDE) {
            if (g[0].startsWith("#")) {
                col.addView(Ui.section(this, g[0].substring(1)));
            } else {
                col.addView(card(g[0], g[1], first));
                first = false;
            }
        }
        col.addView(Ui.creditCard(this));
        setContentView(root);
    }

